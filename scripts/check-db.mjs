function detect(region) {
  if (!region) return null;
  const r = region.toLowerCase();
  const tVil = PROVINCE_GROUPS.find(p => p.key === "toshkent_vil");
  if (tVil && tVil.kw.some(k => r.includes(k))) return "toshkent_vil";
  for (const p of PROVINCE_GROUPS) {
    if (p.key === "toshkent_vil") continue;
    if (p.kw.some(k => r.includes(k))) return p.key;
  }
  return null;
}

const all = await db.client.groupBy({
  by: ["region"],
  _count: { _all: true },
  orderBy: { region: "asc" },
});

const byProvince = {};
const unmatched = [];

for (const g of all) {
  const prov = detect(g.region);
  if (!prov) {
    unmatched.push(g);
  } else {
    byProvince[prov] = (byProvince[prov] || 0) + g._count._all;
  }
}

console.log("=== Viloyatlar bo'yicha (DB da hozir) ===");
for (const [k, v] of Object.entries(byProvince).sort((a,b) => b[1]-a[1])) {
  const label = PROVINCE_GROUPS.find(p => p.key === k)?.key ?? k;
  console.log(`  ${label}: ${v} ta`);
}

console.log(`\n=== Hech qaysi viloyatga tushmagan (${unmatched.length} xil region) ===`);
for (const g of unmatched.sort((a,b) => b._count._all - a._count._all)) {
  console.log(`  "${g.region}"  →  ${g._count._all} ta`);
}

